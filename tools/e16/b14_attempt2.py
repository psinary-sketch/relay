W3 = np.exp(2j * np.pi / 3)


def dft(N):
    return np.exp(2j * np.pi * np.outer(np.arange(N), np.arange(N)) / N) / np.sqrt(N)


def group_alg_mult(x):
    """multiplication-by-x matrix on C[Z/3], x a length-3 coefficient vector."""
    M = np.zeros((3, 3), dtype=complex)
    for i in range(3):
        for j in range(3):
            M[(i + j) % 3, j] += x[i]
    return M


def char_spectrum(x):
    return [sum(x[c] * W3 ** (k * c) for c in range(3)) for k in range(3)]


