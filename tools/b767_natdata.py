"""b767 (R377)(4)(d) L11b: THE FACTORIZATION OF EACH INTEGER FROM 1 TO 16,390, GENERATED FOR THE KERNEL (data/b767_plan.txt :92-:94).

For each m from 1 to 16,390 the list of its prime factors with their exponents, (q, e) by ascending q, the empty list at 1. The kernel
reads it through SIDEExplicitFormula/Window/LogNatBase.lean: natChk m L checks, list by list from m, that the factors' product is the
list's index and that each factor is a key of L10's tree of the primes below 16,391 (LPTree.facOK 16391, the keys the primes up to
16,390 of tools/b767_logdata.py). The lists are written as five runs of 3,278, each checked by the kernel in its own declaration within
KT_CAP 4,100 (tools/b766_kdata.py :65), with each run's length; nfac m reads m's list from its run, and nfac_spec carries the checks to
each m. The hand file SIDEExplicitFormula/Window/LogNat.lean gives logNat_eq, log m equal to its factors' weighted sum of logarithms,
and logNat_bounds from L10's ends.

Commands:
  control   the controls alone, nothing written
  write     the controls, then the kernel's data file and the bank data/b767_natdata.txt
Nothing is computed at a zero; no window coefficient, no K(n) and no combination r is read or printed."""
import sys, os, hashlib

from b767_logdata import primes_upto, factor

KPATH = 'D:/SIDE-explicit-formula'
OUT = 'SIDEExplicitFormula/Window/LogNatData.lean'
BASE = 'SIDEExplicitFormula.Window.LogNatBase'
BANK = 'data/b767_natdata.txt'
NMAX = 16390
BOUND = 16391           # ### LogNatBase.lean natChk: LPTree.facOK 16391
RUN = 3278              # ### five runs of 3,278 = 16,390
NAMES = 'ABCDE'
KT_CAP = 4100
NL = '\n'


def build():
    keys = primes_upto(NMAX)
    tab = {m: factor(m) for m in range(1, NMAX + 1)}
    return keys, tab


def runs():
    """[(name, start, length)] of the five runs."""
    return [(NAMES[k], 1 + k * RUN, RUN) for k in range(len(NAMES))]


def fac_prod(f):
    out = 1
    for q, e in f:
        out *= q ** e
    return out


def nat_chk(keyset, m, L):
    """the kernel's natChk, read in Python: each list's product its index from m, each factor a key below BOUND."""
    for f in L:
        if fac_prod(f) != m:
            return False
        if not all(q in keyset and q < BOUND for q, _e in f):
            return False
        m += 1
    return True


def nfac(blocks, m):
    """the kernel's nfac, read in Python: the run by m's place, then its list."""
    for _nm, start, n, L in blocks:
        if m < start + n:
            return L[m - start] if 0 <= m - start < len(L) else []
    _nm, start, n, L = blocks[-1]
    return L[m - start] if 0 <= m - start < len(L) else []


def blocks_of(tab):
    return [(nm, s, n, [tab[m] for m in range(s, s + n)]) for nm, s, n in runs()]


def top_places(text):
    """the places of each top-level list literal: its commas at depth one, plus one (tools/b767_controls.py list_sizes)."""
    sizes, depth, n = [], 0, 0
    for ch in text:
        if ch == '[':
            depth += 1
            if depth == 1:
                n = 1
        elif ch == ']' and depth:
            depth -= 1
            if depth == 0:
                sizes.append(n)
        elif ch == ',' and depth == 1:
            n += 1
    return sizes


def entry_text(f):
    return '[' + ', '.join('(%d, %d)' % (q, e) for q, e in f) + ']'


def lean_text(blocks):
    out = ['import %s' % BASE, '',
           '/-!',
           '# L11b, its data: the factorization of each integer from 1 to 16,390',
           '',
           'Generated by the relay`s tools/b767_natdata.py (b767, `(R377)`(4)(d)). For each `m` from 1 to 16,390 the list of its prime factors',
           'with their exponents, `(q, e)` by ascending `q`, in five runs of 3,278; each run checked by the kernel with `natChk` from its first',
           'index (each list`s product its index, each factor a key of the primes` tree below 16,391), each run`s length beside it.',
           '`nfac m` reads `m`s list from its run and `nfac_spec` carries the checks to each `m`.',
           '-/',
           '',
           'namespace SIDEExplicitFormula.Window',
           '']
    for nm, s, n, L in blocks:
        out.append('/-- The factorizations of %d to %d. -/' % (s, s + n - 1))
        out.append('def nf%s : List (List (ℕ × ℕ)) := [' % nm)
        for i, f in enumerate(L):
            out.append('  ' + entry_text(f) + (',' if i < len(L) - 1 else ']'))
        out.append('')
    for nm, s, n, L in blocks:
        out.append('theorem nf_ok_%s : natChk %d nf%s = true := by decide +kernel' % (nm, s, nm))
        out.append('')
        out.append('theorem nf_len_%s : nf%s.length = %d := by decide +kernel' % (nm, nm, n))
        out.append('')
    out.append('/-- The factorization of `m`, read from its run. -/')
    out.append('def nfac (m : ℕ) : List (ℕ × ℕ) :=')
    for k, (nm, s, n, L) in enumerate(blocks):
        if k < len(blocks) - 1:
            out.append('  if m < %d then natAt nf%s (m - %d) else' % (s + n, nm, s))
        else:
            out.append('  natAt nf%s (m - %d)' % (nm, s))
    out.append('')
    out.append('/-- Each `m` from 1 to 16,390: its factors` product is `m`, each factor a key of the primes` tree below 16,391. -/')
    out.append('theorem nfac_spec (m : ℕ) (h1 : 1 ≤ m) (h2 : m ≤ 16390) :')
    out.append('    facProd (nfac m) = m ∧ lpTree.facOK 16391 (nfac m) = true := by')
    out.append('  unfold nfac')
    out.append('  split_ifs with hA hB hC hD')
    for nm, s, n, L in blocks:
        out.append('  · have h := natChk_spec nf%s %d (m - %d) nf_ok_%s (by rw [nf_len_%s]; omega)' % (nm, s, s, nm, nm))
        out.append('    rwa [show %d + (m - %d) = m by omega] at h' % (s, s))
    out.append('')
    out.append('end SIDEExplicitFormula.Window')
    out.append('')
    return NL.join(out)


def controls(keys, tab):
    rows = []
    keyset = set(keys)

    def c(name, ok, det):
        rows.append((name, bool(ok), det))

    c('(1) the keys: the primes up to 16,390 as tools/b767_logdata.py reads them, 1,900, the largest 16,381, each below 16,391',
      len(keys) == 1900 and keys[-1] == 16381 and all(q < BOUND for q in keys), '%d keys, the largest %d' % (len(keys), keys[-1]))
    bad = [m for m in tab if fac_prod(tab[m]) != m]
    c('(2) each list`s product its index, m from 1 to 16,390', not bad and len(tab) == NMAX, 'lists %d, products wrong %d' % (len(tab), len(bad)))
    nk = [m for m in tab if not all(q in keyset for q, _e in tab[m])]
    order = [m for m in tab if any(a[0] >= b[0] for a, b in zip(tab[m], tab[m][1:])) or any(e < 1 for _q, e in tab[m])]
    c('(3) each factor a key, the factors ascending and each exponent at least 1', not nk and not order,
      'a factor not a key %d ; out of order or an exponent below 1 %d' % (len(nk), len(order)))
    bl = blocks_of(tab)
    starts = [(nm, s, n) for nm, s, n, _L in bl]
    c('(4) the runs: five of 3,278 from 1, 3,279, 6,557, 9,835 and 13,113, the last ending at 16,390, each within KT_CAP 4,100',
      [s for _nm, s, _n in starts] == [1, 3279, 6557, 9835, 13113] and starts[-1][1] + starts[-1][2] - 1 == NMAX
      and all(n <= KT_CAP for _nm, _s, n in starts), str(starts))
    chk = [nat_chk(keyset, s, L) for _nm, s, _n, L in bl]
    c('(5) the kernel`s natChk read in Python over each run from its first index', all(chk), str(chk))
    probes = [1, 2, 3278, 3279, 6556, 6557, 9834, 9835, 13112, 13113, 16381, 16384, 16390]
    got = [nfac(bl, m) == tab[m] for m in probes]
    c('(6) the kernel`s nfac read in Python at each run`s two ends and at 1, 2, 16,381, 16,384 and 16,390', all(got),
      '%d of %d' % (sum(got), len(got)))
    # ### four plants, each refused by the conjunct planted
    A = bl[0][3]
    p1 = list(A)
    p1[11] = [(2, 2), (3, 1), (5, 1)]            # m = 12 read as 60: the product
    p2 = list(A)
    p2[3] = [(4, 1)]                              # m = 4 as 4^1: 4 not a key
    p3 = list(A)
    p3[0], p3[1] = p3[1], p3[0]                   # 1 and 2 exchanged: the index
    p4 = [tab[m] for m in range(2, 2 + RUN)]      # the run from 2 read from 1: shifted by one
    pl = [nat_chk(keyset, 1, p1), nat_chk(keyset, 1, p2), nat_chk(keyset, 1, p3), nat_chk(keyset, 1, p4)]
    c('(7) four planted runs each refused (12 read as 60 ; 4 as 4^1, not a key ; 1 and 2 exchanged ; a run shifted by one)',
      pl == [False, False, False, False], str(pl))
    text = lean_text(bl)
    places = top_places(text)
    c('(8) the kernel`s file: its first line its import, each top-level list within KT_CAP 4,100 (the largest %d), five runs and five of each '
      'theorem' % max(places), text.split(NL)[0] == 'import %s' % BASE and max(places) <= KT_CAP and text.count('theorem nf_ok_') == 5
      and text.count('theorem nf_len_') == 5 and text.count('def nf') == 6, 'places %d lists, the largest %d' % (len(places), max(places)))
    return rows, bl, text


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    if cmd not in ('control', 'write'):
        print('usage: b767_natdata.py control | write')
        return 2
    keys, tab = build()
    rows, bl, text = controls(keys, tab)
    good = sum(1 for _, ok, _ in rows if ok)
    for nm, ok, det in rows:
        print('  %-140s %s ; %s' % (nm, 'AS WANTED' if ok else 'NOT AS WANTED', det))
    print('### CONTROLS %d OF %d AS WANTED' % (good, len(rows)))
    nf = sum(len(tab[m]) for m in tab)
    print('  the factors: %d pairs over %d lists, the most in one list %d' % (nf, len(tab), max(len(tab[m]) for m in tab)))
    if good != len(rows):
        print('### NOTHING WRITTEN: a control not as wanted')
        return 1
    if cmd == 'control':
        return 0
    data = text.encode('utf-8')
    path = os.path.join(KPATH, OUT)
    with open(path, 'wb') as f:
        f.write(data)
    sha = hashlib.sha256(data).hexdigest()
    nlines = text.count(NL)
    bank = ['b767 -- (R377)(4)(d) L11b: THE FACTORIZATION OF EACH INTEGER FROM 1 TO 16,390, GENERATED FOR THE KERNEL (tools/b767_natdata.py '
            'write)', '', '## THE CONTROLS']
    for nm, ok, det in rows:
        bank.append('  %s: %s ; %s' % (nm, 'AS WANTED' if ok else 'NOT AS WANTED', det))
    bank += ['  CONTROLS %d OF %d AS WANTED' % (good, len(rows)), '', '## THE DATA',
             '  lists %d (m from 1 to 16,390) ; factor pairs %d, the most in one list %d ; the keys the 1,900 primes up to 16,390' %
             (len(tab), nf, max(len(tab[m]) for m in tab)),
             '  runs %s' % [(nm, s, n) for nm, s, n, _L in bl],
             '  the kernel`s file %s: %d lines, %d bytes, sha256 %s' % (OUT, nlines, len(data), sha),
             '', 'Nothing computed at a zero; no window coefficient, no K(n) and no combination r read or printed.', '']
    with open(BANK, 'w', encoding='utf-8', newline='\n') as f:
        f.write(NL.join(bank))
    print('  WRITTEN: %s (%d lines, %d bytes, sha256 %s) ; %s' % (OUT, nlines, len(data), sha[:16], BANK))
    return 0


if __name__ == '__main__':
    sys.exit(main())
