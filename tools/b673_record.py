def _clause(n):
    r = _ruling()
    m = re.search(r'\n\(%d\) (.*?)(?=\n\(%d\) |\Z)' % (n, n + 1), r, re.S)
    if not m:
        sys.exit('### (R283)(%d) NOT FOUND IN THE FERRY BANK -- NOTHING WRITTEN' % n)
    return ' '.join(m.group(1).split())


