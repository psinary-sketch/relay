def _ruling():
    t = rdn('b673_ferry.txt')
    i, j = t.find('RULING (R283) BEGIN'), t.find('RULING (R283) END')
    if i < 0 or j < i:
        sys.exit('### THE FERRY BANK CARRIES NO (R283) -- NOTHING WRITTEN')
