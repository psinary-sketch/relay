def excepted(kind, x, y, z, o):
    """### b739: a place the byline exception takes: the byline's own kind, no address, each other target within the exception's count."""
    return kind == BYLINE_KIND and x == 0 and y <= BYLINE_MAX and z <= BYLINE_MAX and o <= BYLINE_MAX


def split_byline(diff):
    """### b739: the diff less BYLINE_FILE's section, and that section's added lines."""
    rest, by = [], []
    for sec in ('\n' + diff).split('\ndiff --git '):
        (by if sec.split(NL, 1)[0].endswith(tuple('/' + f_ for f_ in BYLINE_FILES)) else rest).append(sec)
    return '\ndiff --git '.join(rest), added(NL.join(by))


def places():
    """(kind, label, text): the new text the act wrote, by place."""
    out = []
    for repo, name, pre in ((ROOT, 'relay', K.PRE_RELAY), (PP, 'PLACE-papers', K.PRE_PP)) + tuple((r, n, p) for r, n, p in SITTING_REPOS):
        for h in [x for x in git(repo, 'rev-list', '--reverse', pre if '..' in pre else '%s..HEAD' % pre).split(NL) if x.strip()]:
            out.append(('commit fields', '%s %s' % (name, h[:8]), git(repo, 'log', '-1', '--format=%an%n%ae%n%cn%n%ce', h)))
            out.append(('commit message', '%s %s' % (name, h[:8]), git(repo, 'log', '-1', '--format=%B', h)))
            rest, by = split_byline(git(repo, 'show', '--format=', '--no-color', '--no-ext-diff', h))
            out.append(('commit added lines', '%s %s' % (name, h[:8]), added(rest)))
            if by:
                out.append((BYLINE_KIND, '%s %s' % (name, h[:8]), by))
        # ### b748, (R358)(3)(ii): the index read as its own kind (the staged set, HEAD to the index) and the working tree apart (the index to the
        # ### working tree); before, one `git diff HEAD` read both under the working tree's one place per repository, so a staged file moved no count
        rest, by = split_byline(git(repo, 'diff', '--cached', '--no-color', '--no-ext-diff'))
        out.append(('staged added lines', name, added(rest)))
        if by:
            out.append((BYLINE_KIND, name + ' staged', by))
        rest, by = split_byline(git(repo, 'diff', '--no-color', '--no-ext-diff'))
        out.append(('working tree added lines', name, added(rest)))
        if by:
            out.append((BYLINE_KIND, name + ' working tree', by))
    tracked = set(git(ROOT, 'ls-files', '--', 'data/').split(NL))
    for f in sorted(os.listdir(D)):
        p = 'data/' + f
        if f.startswith(ACT + '_') and os.path.isfile(os.path.join(D, f)) and p not in tracked and not f.endswith(('.gz', '.png')):
            out.append(('untracked bank', p, open(os.path.join(D, f), encoding='utf-8', errors='replace').read()))
    # ### b748, (R358)(3)(ii): the act's untracked tools (its own under tools/, its module, a new standing tool), which no kind read before their add
    for p in sorted(x for x in git(ROOT, 'ls-files', '--others', '--exclude-standard', '--', 'tools/').split(NL) if x.strip()):
        b_ = p.split('/')[-1]
        if (b_.startswith(ACT + '_') or p == 'tools/acts/%s.py' % ACT or p.startswith('tools/standing/')) and os.path.isfile(os.path.join(ROOT, *p.split('/'))):
            out.append(('untracked tool', p, open(os.path.join(ROOT, *p.split('/')), encoding='utf-8', errors='replace').read()))
    return out


def scan(*a):
    t0 = time.time()
    addr, name, uname, orcid = previous_address(), author_name(), previous_username(), author_orcid()
    ctl = [('a planted line carrying the address', count('x %s y' % addr, addr) == 1 and count('x %s y' % addr, name) == 0),
           ('a planted line carrying the name', count('x %s y' % name, name) == 1 and count('x %s y' % name, addr) == 0),
           ('a clean line', count('the noreply form ' + NOREPLY, addr) == 0 and count('the noreply form ' + NOREPLY, name) == 0
            and count('the noreply form ' + NOREPLY, uname) == 0)]
    s = 'control %s between %s end %s' % (addr, uname, orcid)   # ### b739: the author's word's control, one string built and dropped in memory
    ctl.append(('the address and the previous user.name, once each', count(s, addr) == 1 and count(s, uname) == 1))
    ctl.append(('a planted line carrying the ORCID', count('x %s y' % orcid, orcid) == 1 and count('x %s y' % orcid, addr) == 0 and count('the noreply form ' + NOREPLY, orcid) == 0))
    ctl.append(('a moved line is not added, a new line and a second copy are', added('-a\n+a\n+b') == 'b' and added('-a\n+a\n+a') == 'a'))
    ctl.append(('the ORCID excepted in the byline alone', all(excepted(k, 0, 0, 0, count(s, orcid)) == (k == BYLINE_KIND)
                                                             for k in (BYLINE_KIND, 'commit added lines', 'commit message', 'untracked bank'))))
    ctl.append(('N5 read in both rulings` wordings (b760 (f))', n5_holds('(N5) x; no new occurrence beyond a byline under I-23')
                and n5_holds("(N5) x; no identifier of the author beyond the edition's byline and two self-citations")
                and not n5_holds('(N5) x; no identifier of the author in anything the act writes') and not n5_holds('(N4) beyond a byline')
                and RULING_N5 == 'R380' and BYLINE_HELD and NO_BYLINE and BYLINE_FILES == ()
                and n5_writes_none('(N5) x; beyond a byline, and this act writes no byline') and not n5_writes_none('(N5) x; beyond a byline under I-23')
                and n5_writes_none('(N5) x; beyond a byline, the copies of the papers in the repository of (7) carrying theirs as written')
                and n5_writes_none('(N5) x; beyond a byline, the copies of the papers in that repository carrying theirs as written')
                and n5_writes_none("(N5) x; beyond a byline, the copies of the papers in the Project's repository carrying theirs as written")))   # ### b769 step zero: (R379)'s wording, the Project's repository by its name ((R380)'s the same). b764 defect (d), b766 step zero: (R376)'s N5 (its line N5_AT, read at run time) holds the exception in its words and names copies in the Project's repository alone ("that repository"), so no file is excepted; (R375)'s wording kept in the control beside it
    del s
    L = ['%s -- (R332)(9)(i): NO NEW OCCURRENCE OF THE AUTHOR`S NAME OR E-MAIL ADDRESS (%s)' % (ACT, time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())),
         '', '### the previous address read from relay`s history to %s (author and committer e-mails less the noreply form: one address), the' % K.PRE_RELAY[:8],
         '### name from the monograph`s byline at run time, the previous user.name from 30c0b3c8`s author field, the ORCID from the monograph`s head (b739); all held in memory, none printed. New text only: the commits from relay %s and' % K.PRE_RELAY[:8],
         '### PLACE-papers %s to HEAD (fields, messages, added lines), the staged set (HEAD to the index), the working tree`s added lines (the index to the tree), the untracked banks and tools of %s.' % (K.PRE_PP[:8], ACT), '',
         '## THE CONTROLS FIRST']
    L += ['  %-40s %s' % (w, 'AS WANTED' if ok else 'NOT AS WANTED') for w, ok in ctl]
    if not all(ok for _w, ok in ctl):
        print(NL.join(L))
        sys.exit('### A CONTROL NOT AS WANTED -- NOTHING COUNTED')
    P = places()
    by = {}
    exc = []
    na = nn = nu = no = 0
    for kind, label, text in P:
        x, y, z, o = count(text, addr), count(text, name), count(text, uname), count(text, orcid)
        if excepted(kind, x, y, z, o):   # ### b739: named in the bank, not counted; beyond this it counts
            exc.append('  %s: %s: address %d ; name %d ; previous user.name %d ; ORCID %d (at most %d)' % (kind, label, x, y, z, o, BYLINE_MAX))
            continue
        na, nn, nu, no = na + x, nn + y, nu + z, no + o
        k = by.setdefault(kind, [0, 0, 0, 0, 0])
        k[0] += 1
        k[1] += x
        k[2] += y
        k[3] += z
        k[4] += o
    L += ['', '## THE PLACES READ, BY KIND (places ; address ; name ; previous user.name ; ORCID)']
    L += ['  %-28s %4d ; %d ; %d ; %d ; %d' % (k, v[0], v[1], v[2], v[3], v[4]) for k, v in sorted(by.items())]
    hits = sorted(set('%s %s' % (kind, label) for kind, label, text in P if kind != BYLINE_KIND and (count(text, addr) or count(text, name) or count(text, uname) or count(text, orcid))))
    L += ['', '## THE PLACES WITH AN OCCURRENCE (by place, never the text): %s' % ('; '.join(hits) if hits else 'NONE')]
    # ### b765, (R375)(3), tools/standing/ v1.35.4: the repositories whose commits, staged set and working tree this run read, by name; a
    # ### kernel's commit through tools/standing/commit.py wants its kernel named here
    L += ['', '## THE REPOSITORIES READ (commits from their base, the staged set, the working tree): %s' % '; '.join(
        ['relay', 'PLACE-papers'] + [n for _r, n, _p in SITTING_REPOS])]
    L += ['', exception_head(ACT, RULING_N5, N5_AT, BYLINE_FILES, bool(exc))] + exc   # ### b765, (R375)(5) [K2]: the clause and line read at run time
    L += ['', 'PREVIOUS ADDRESS: %d' % na, 'THE AUTHOR`S NAME: %d' % nn, 'PREVIOUS NAME: %d' % nu, 'THE ORCID: %d' % no, '',
          '### ### **PREVIOUS ADDRESS: %d ; THE AUTHOR`S NAME: %d ; PREVIOUS NAME: %d ; THE ORCID: %d ; PLACES %d ; CONTROLS %d OF %d AS WANTED ; %d s.**' % (
              na, nn, nu, no, len(P), len(ctl), len(ctl), int(time.time() - t0))]
    text = NL.join(L)
    if addr in text.lower() or name.lower() in text.lower() or uname.lower() in text.lower() or orcid.lower() in text.lower():
        sys.exit('### THE BANK WOULD CARRY THE ADDRESS OR THE NAME -- NOTHING PRINTED OR WRITTEN')
    print(text)
    if '--bank' in a:
        # ### v1.9.0, (R349)(2)(v): after the lock the run is written back to the scan's post-lock bank in the same form, the locked bank unedited
        import standing.act as SA
        locked = os.path.exists(os.path.join(D, '%s_lockgate.json' % ACT))
        nm = SA.scan_bank_name(ACT, locked)
        p = os.path.join(D, nm)
        body = SA.scan_append(open(p, encoding='utf-8').read() if os.path.exists(p) else '', time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()), text) if locked else text + NL
        with open(p + '.tmp', 'wb') as fh:
            fh.write(body.encode('utf-8'))
        os.replace(p + '.tmp', p)
        print('written data/%s' % nm)
    return na, nn, nu, no


