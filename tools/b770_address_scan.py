def added(diff):
    """the lines a diff adds, less any it removes verbatim: a line the diff shows moved is no new occurrence (b739 [88]: a byline standing once at HEAD and once after, shown - and +)."""
    gone, out = {}, []
    for l in diff.split(NL):
        if l.startswith('-') and not l.startswith('---'):
            gone[l[1:]] = gone.get(l[1:], 0) + 1
    for l in diff.split(NL):
        if l.startswith('+') and not l.startswith('+++'):
            if gone.get(l[1:], 0):
                gone[l[1:]] -= 1
            else:
                out.append(l[1:])
    return NL.join(out)


