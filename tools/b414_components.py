def read(p):
    try:
        with open(p, 'rb') as fh:
            return fh.read().decode('utf-8', 'replace')
    except Exception as exc:
        QFAIL.append('%s : %s' % (os.path.basename(p), exc))
        return ''


def q(label, path, needle):
    """### **A LIVE QUOTE.** ### The needle is sought in the bytes on disk NOW, and a miss is a
    ### COUNTED FAILURE -- not a line the report quietly omits."""
    src = read(path)
    if needle in src:
        return True
    QFAIL.append('%s -- %r not in %s' % (label, needle[:56], os.path.basename(path)))
    say('      ### **LIVE-QUOTE MISS** -- %s' % label)
    return False


def wrap(text, width):
    """### **WRAP AT WORD BOUNDARIES.** ### `b410` paid for this once: a fixed-width slice split
    ### `that` into `t hat`, and a live-quote arm then measured the WRAPPER instead of the text.
    ### This act committed it again on the seal's own caveat, splitting `residue` into `a re` /
    ### `sidue`. ### **A REPORT THAT BREAKS ITS SUBJECT'S WORDS IS NOT QUOTING ITS SUBJECT.**
    """
    out, line = [], ''
    for w in (text or '').split(' '):
        if line and len(line) + 1 + len(w) > width:
            out.append(line)
            line = w
        else:
            line = (line + ' ' + w) if line else w
    if line:
        out.append(line)
    return out


def code_of(src):
    """### **STRIP COMMENTS AND DOCSTRINGS BEFORE SCANNING SOURCE** (`b410`'s `G-NOBORROWEDBAR`
    ### fired on its own explanation). ### Lean block comments are `/- ... -/`, lines are `--`."""
    s = re.sub(r'/-.*?-/', ' ', src, flags=re.S)
    return re.sub(r'(?m)--.*$', ' ', s)


