def run_build():
    import subprocess
    ALLP = os.path.join(KERN, 'AllPrints.lean')
    MODULE = 'SinglePrimeFactor'
    PFXOUT = os.path.join(D, 'b414_prints_prefix.txt')
    BL = []

    def rec(s=''):
        BL.append(s)
        print(s, flush=True)

    def rb(p):
        with open(p, 'rb') as fh:
            return fh.read()

    def wb(p, data):
        open(p + '.tmp', 'wb').write(data)
        os.replace(p + '.tmp', p)

    rec('=' * 100)
    rec('b414 BUILD PHASE -- THE PROFILE REGENERATED, PRIOR ONE PROVED A TRUE BYTE PREFIX.')
    rec('=' * 100)
    before_bytes = rb(PRINTS)
    before_lines = before_bytes.decode('utf-8', 'replace').splitlines()
    rec('  prior profile : %d bytes, %d lines' % (len(before_bytes), len(before_lines)))
    src = read(NEW)
    terms = re.findall(r'(?m)^theorem\s+(\w+)', code_of(src))
    rec('  terminals to print : %d' % len(terms))
    allp = io.open(ALLP, encoding='utf-8').read()
    lines = allp.splitlines()
    if ('import %s' % MODULE) in allp:
        rec('  import already present; not re-added.')
    else:
        li = max(i for i, ln in enumerate(lines) if ln.startswith('import '))
        lines.insert(li + 1, 'import %s' % MODULE)
        rec('  import inserted after line %d (the last import); 0 lines deleted' % (li + 1))
    added = 0
    for t in terms:
        stmt = '#print axioms %s.%s' % (MODULE, t)
        if stmt not in allp:
            lines.append(stmt)
            added += 1
    rec('  `#print axioms` lines appended at the END : %d' % added)
    wb(ALLP, (NL.join(lines) + NL).encode('utf-8'))
    rec('')
    rec('  running `lean AllPrints.lean` -- ### **AXIOM_PRINTS.txt IS ITS STDOUT.**')
    env = dict(os.environ, LEAN_PATH='build')
    r = subprocess.run(['lean', 'AllPrints.lean'], cwd=KERN, env=env,
                       capture_output=True, text=True, encoding='utf-8', errors='replace')
    rec('  exit code : %d' % r.returncode)
    if r.stderr.strip():
        rec('  ### STDERR (first 800 chars):')
        rec('      %s' % r.stderr[:800].replace(NL, NL + '      '))
    io.open(BUILD, 'w', encoding='utf-8', newline=NL).write(
        'exit=%d%sstdout bytes=%d%sstderr:%s%s%s'
        % (r.returncode, NL, len(r.stdout), NL, NL, r.stderr[:4000], NL))
    if r.returncode != 0:
        rec('  ### ### **BUILD DID NOT EXIT 0 -- REFUSING TO OVERWRITE THE PROFILE.**')
        io.open(PFXOUT, 'w', encoding='utf-8', newline=NL).write(NL.join(BL) + NL)
        return 2
    new_bytes = r.stdout.replace(chr(13) + NL, NL).encode('utf-8')
    after_lines = new_bytes.decode('utf-8').splitlines()
    rec('  new profile   : %d bytes, %d lines' % (len(new_bytes), len(after_lines)))
    prefix_ok = new_bytes.startswith(before_bytes)
    rec('')
    rec('  ### CLAUSE 1 -- ### **TRUE BYTE PREFIX : %s**' % ('YES' if prefix_ok else 'NO'))
    if not prefix_ok:
        n = min(len(before_bytes), len(new_bytes))
        i = next((k for k in range(n) if before_bytes[k] != new_bytes[k]), n)
        rec('      first differing byte at offset %d' % i)
        rec('      prior : %r' % before_bytes[max(0, i - 60):i + 60])
        rec('      new   : %r' % new_bytes[max(0, i - 60):i + 60])
    gained = len(after_lines) - len(before_lines)
    count_ok = (gained == len(terms))
    rec('  ### CLAUSE 2 -- lines gained %d, terminals added %d : ### **%s**'
        % (gained, len(terms), 'EQUAL' if count_ok else 'NOT EQUAL'))
    axiom_lines = [ln for ln in after_lines if 'depends on axioms' in ln]
    rec('  ### CLAUSE 3 -- lines reporting a NON-EMPTY profile : ### **%d**' % len(axiom_lines))
    for ln in axiom_lines[:10]:
        rec('      %s' % ln)
    rec('')
    for t in terms:
        hit = [ln for ln in after_lines if ("'%s.%s'" % (MODULE, t)) in ln]
        rec('  %-44s %s' % (t, hit[0] if hit else '### **NOT PRINTED**'))
    ok = prefix_ok and count_ok and not axiom_lines and all(
        any(("'%s.%s'" % (MODULE, t)) in ln for ln in after_lines) for t in terms)
    rec('')
    rec('  ### ### **VERDICT : %s**' % ('CLEAN ON ALL THREE CLAUSES' if ok else 'REFUSED'))
    if ok:
        wb(PRINTS, new_bytes)
        rec('  profile written : AXIOM_PRINTS.txt')
    else:
        rec('  ### ### **PROFILE NOT OVERWRITTEN.**')
    rec('=' * 100)
    io.open(PFXOUT, 'w', encoding='utf-8', newline=NL).write(NL.join(BL) + NL)
    return 0 if ok else 1


