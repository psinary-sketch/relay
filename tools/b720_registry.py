def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'dry'
    raw = open(REG, 'rb').read()
    bom = raw.startswith(b'\xef\xbb\xbf')
    text = raw[3:].decode('utf-8') if bom else raw.decode('utf-8')
    nl = '\r\n' if '\r\n' in text else '\n'
    print('REGISTRY: %d bytes, BOM %s, newline %r, ends with newline %s' % (len(raw), bom, nl, text.endswith(nl)))
    sep = '' if text.endswith(nl) else nl
    app = sep + build(text, nl)
    if mode == 'dry':
        print(app)
        print('DRY: nothing written')
        return
    if mode != 'write':
        raise SystemExit('usage: dry | write')
    new = raw + app.encode('utf-8')
    open(REG, 'wb').write(new)
    back = open(REG, 'rb').read()
    additive = back.startswith(raw) and back == new
    print('READ BACK: %d bytes; the old bytes a prefix of the new: %s' % (len(back), additive))
    if not additive:
        raise SystemExit('NOT ADDITIVE')
    old_l = text.replace('\r', '').split('\n')
    new_l = (back[3:] if bom else back).decode('utf-8').replace('\r', '').split('\n')
    d = list(difflib.unified_diff(old_l, new_l, 'REGISTRY.md (before)', 'REGISTRY.md (after)', lineterm=''))
    minus = [x for x in d if x.startswith('-') and not x.startswith('---')]
    body = ['b720 -- (R330)(5)(i): the REGISTRY diff, banked by tools/b720_registry.py write (%s)' % DATE,
            'REGISTRY.md %d -> %d bytes; the old bytes a prefix of the new: %s; removed lines: %d' % (len(raw), len(back), additive, len(minus)), ''] + d
    s = '\n'.join(body) + '\n'
    with io.open(DIFF, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(s)
    print('BANKED %s: %d lines, removed lines %d' % (DIFF, len(body), len(minus)))


main()
