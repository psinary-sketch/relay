def words(path):
    return len(io.open(PP + path, encoding='utf-8').read().split())


def build(text, nl):
    L = text.replace('\r', '').split('\n')
    ids, seen = [], set()
    for i, l in enumerate(L, 1):
        m = ROW_ID.match(l)
        if not m:
            continue
        cells = [c.strip() for c in l.split('|')]
        rid = m.group(1)
        if len(cells) > 3 and cells[3].startswith('`REGISTRY.md:'):
            continue                                   # b618's version-cell rows point at a row; they are not rows of their own
        if rid in seen or rid == 'P-ZONE':
            continue
        seen.add(rid)
        ids.append((rid, i))
    print('MATCHER YIELD: %d row ids (b618 pointer rows, repeats and the patent row P-ZONE set aside)' % len(ids))
    for nid, _, f, _, _, _ in NEW_ROWS:
        if nid in seen:
            raise SystemExit('REFUSED: the new id %s already names a row' % nid)
        if not os.path.exists(PP + f):
            raise SystemExit('REFUSED: %s is absent' % f)
        if f in text:
            raise SystemExit('REFUSED: %s is already named in REGISTRY' % f)
    for w in WAVE1_IDS:
        if w not in seen and w not in CHECKPOINTS and w not in [r[0] for r in NEW_ROWS]:
            raise SystemExit('REFUSED: wave-1 id %s names no row' % w)
