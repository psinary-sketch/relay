# -*- coding: utf-8 -*-
"""b680_rules_index.py -- (R290)(5)(ii)-(iii): THE RULES INDEX, GENERATED. Rows are rules: the act that banked it, its row, its text's head (the
row's first sentence as the bank writes it) and the standing arm that enforces it, or NONE.

### The banks read: every data/b67N_rules.txt that exists (b670, b671, b672, b673, b674, b675, b677, b678; b676 and b679 banked none -- the
### author's answer at b680's step zero). A row is a line `ROW n -- ...` (b670-b672's form) or `  (n) ...` (b673's on). The arm column is
### this tool's table ARMS below, each entry read by hand against the sealed suite's standing arms (tools/b679_checks.py, STANDING at :311,
### each arm's `reads` field); a rule no standing arm reads is NONE. Run: `python -X utf8 tools/b680_rules_index.py` -> data/b680_rules_index.txt
### (.json); it writes nothing else. A bank regenerated by this tool, not a hand-written document.
"""
import io
import json
import os
import re
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'data')
NL = chr(10)
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

ROW_RE = re.compile(r'^(?:ROW (\d+) -- |  \((\d+)\) )(.*)$')
# ### (act, row) -> (the standing arm, what of the rule it reads); every row absent here is NONE
ARMS = {
    ('b670', 4): ('G-BRANCHES-DELETED', 'the branches the ruling names absent from each repository`s lists, local and remote-tracking, and the '
                                         'branches bank -- the deletion, not its one-branch-per-command form'),
    ('b670', 5): ('G-NODISCLOSURE-PUBLIC', 'TECHNE-Core`s needle sets over every public byte the act writes -- the withholding`s effect, not the '
                                            'roster reader`s skip'),
}


def banks():
    return sorted(f for f in os.listdir(D) if re.match(r'^b67\d_rules\.txt$', f))


def rows():
    out = []
    for f in banks():
        act = f[:4]
        for i, l in enumerate(io.open(os.path.join(D, f), encoding='utf-8').read().replace(chr(13), '').split(NL), 1):
            m = ROW_RE.match(l)
            if m:
                n = int(m.group(1) or m.group(2))
                head = re.split(r'(?<=[.])\s', m.group(3), maxsplit=1)[0]
                arm = ARMS.get((act, n))
                out.append(dict(act=act, row=n, line=i, bank='data/' + f, head=head, arm=arm[0] if arm else 'NONE', reads=arm[1] if arm else ''))
    return out


def main():
    R = rows()
    absent = ['b67%d_rules.txt' % i for i in range(0, 10) if not os.path.exists(os.path.join(D, 'b67%d_rules.txt' % i))]
    L = ['b680 -- THE RULES INDEX, GENERATED BY tools/b680_rules_index.py (%s)' % time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()), '',
         '### rows are rules: act ; row ; the bank and line ; its head ; the standing arm that enforces it, or NONE (with what of the rule the arm reads).',
         '### banks read %d: %s ; absent (no rules banked by that act): %s' % (len(banks()), ', '.join(banks()), ', '.join(absent) or 'NONE'), '']
    for r in R:
        L.append('  %-5s row %-2d %s :%-3d %s' % (r['act'], r['row'], r['bank'], r['line'], r['head'][:150]))
        L.append('        ARM: %s%s' % (r['arm'], (' -- reads ' + r['reads']) if r['reads'] else ''))
    none = [r for r in R if r['arm'] == 'NONE']
    L += ['', '### THE RULES NO STANDING ARM ENFORCES, FOR THE AUTHOR`S DECISION ON WHICH RECEIVE ARMS (no arm added in this act):']
    L += ['  %s row %d -- %s' % (r['act'], r['row'], r['head'][:120]) for r in none]
    L += ['', '### ### **RULES %d IN %d BANKS ; WITH A STANDING ARM %d ; NONE %d.**' % (len(R), len(banks()), len(R) - len(none), len(none))]
    for n, b in (('b680_rules_index.txt', (NL.join(L) + NL).encode('utf-8')),
                 ('b680_rules_index.json', (json.dumps(dict(rows=R, absent=absent), indent=1, ensure_ascii=False) + NL).encode('utf-8'))):
        p = os.path.join(D, n)
        open(p + '.tmp', 'wb').write(b)
        os.replace(p + '.tmp', p)
    print(L[-1])


if __name__ == '__main__':
    main()
