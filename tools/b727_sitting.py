def zenodo(n, it):
    rec, how = ZEN[n]
    token = os.environ.get('ZENODO_TOKEN')
    if not token:
        sys.exit('### NO ZENODO TOKEN IN THE ENVIRONMENT -- NOTHING WRITTEN')
    before = anon(rec)
    base = 'https://zenodo.org/api/deposit/depositions/%s' % rec
    st, j = http(base + '/actions/edit', 'POST', None, token)
    if st not in (200, 201, 202):
        sys.exit('### actions/edit: %s %s' % (st, str(j)[:400]))
    st, dep = http(base, 'GET', None, token)
    if st != 200:
        http(base + '/actions/discard', 'POST', None, token)
        sys.exit('### the deposition read: %s %s' % (st, str(dep)[:400]))
    meta = dep['metadata']
    prior = dict(meta)
    raw = meta['description']
    if how == 'sub':
        cur, new = it['current'].replace('—', '&mdash;'), it['draft'].replace('—', '&mdash;')
        if raw.count(cur) != 1:
            cur, new = it['current'], it['draft']
        if raw.count(cur) != 1:
            http(base + '/actions/discard', 'POST', None, token)
            sys.exit('### [%d]: the raw description does not carry the CURRENT once -- DISCARDED, nothing edited' % n)
        wanted = raw.replace(cur, new, 1)
    elif how == 'head':
        wanted = '<p>%s</p>%s%s' % (it['draft'], NL, raw)
    else:
        wanted = '%s%s<p>%s</p>' % (raw, NL, it['draft'])
    meta['description'] = wanted
    st, j = http(base, 'PUT', {'metadata': meta}, token)
    if st != 200:
        http(base + '/actions/discard', 'POST', None, token)
        sys.exit('### PUT: %s %s -- DISCARDED, nothing edited' % (st, str(j)[:400]))
    st, dep2 = http(base, 'GET', None, token)
    after = dep2['metadata'] if st == 200 else {}
    moved = sorted(k for k in set(prior) | set(after) if k != 'description' and prior.get(k) != after.get(k))
    if moved:
        http(base + '/actions/discard', 'POST', None, token)
        sys.exit('### THE DRAFT MOVED OTHER FIELDS %s -- DISCARDED, nothing edited' % moved)
    print('  THE DRAFT`S OTHER METADATA FIELDS UNMOVED (%d read)' % len(prior))
    st, j = http(base + '/actions/publish', 'POST', None, token)
    if st not in (200, 201, 202):
        sys.exit('### actions/publish: %s %s' % (st, str(j)[:400]))
    for _ in range(12):
        time.sleep(5)
        back = anon(rec)
        if html.unescape(it['draft']) in html.unescape(back['metadata'].get('description') or ''):
            break
    else:
        sys.exit('### THE ANONYMOUS READ-BACK DOES NOT CARRY THE DRAFT AT [%d] -- HALT, the record to be read by hand' % n)
    bm, am = dict(before['metadata']), dict(back['metadata'])
    bd, ad = bm.pop('description'), am.pop('description')
    bm.pop('relations', None), am.pop('relations', None)
    same_meta = bm == am
    bf = sorted((f.get('key'), f.get('checksum')) for f in before.get('files', []))
    af = sorted((f.get('key'), f.get('checksum')) for f in back.get('files', []))
    same_id = (before['id'], before['doi'], before['metadata'].get('version')) == (back['id'], back['doi'], back['metadata'].get('version'))
    print('  ANONYMOUS READ-BACK: the draft carried ; other metadata %s ; files %s (%d) ; record, DOI, version %s' % (
        'EQUAL' if same_meta else 'DIFFER', 'EQUAL' if bf == af else 'DIFFER', len(af), 'EQUAL' if same_id else 'DIFFER'))
    z = json.load(open(ZBANK, encoding='utf-8')) if os.path.exists(ZBANK) else {}
    z[str(n)] = {'record': rec, 'at': now(), 'description': back['metadata']['description'], 'other_metadata_equal': same_meta, 'files_equal': bf == af,
                 'record_doi_version_equal': same_id, 'files': len(af)}
    with open(ZBANK + '.tmp', 'wb') as fh:
        fh.write((json.dumps(z, ensure_ascii=False, indent=1) + NL).encode('utf-8'))
    os.replace(ZBANK + '.tmp', ZBANK)
    if not (same_meta and bf == af and same_id):
        print('### A FIELD BESIDE THE DESCRIPTION MOVED AT [%d]: bm %s' % (n, sorted(k for k in set(bm) | set(am) if bm.get(k) != am.get(k))))
    return 'Zenodo %s read back anonymously %s (data/b727_zenodo_readback.json [%d]; other metadata %s, files %s, record DOI version %s)' % (
        rec, now(), n, same_meta, bf == af, same_id)


