def identity_scan(repo):
    """the scan at the commit, its bank's last line printed; anything but zero refuses."""
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        na, nn, nu = SCAN.scan()
    print('  SCAN:', buf.getvalue().strip().split(NL)[-1])
    if na or nn or nu:
        print(buf.getvalue())
        sys.exit('### THE IDENTITY SCAN IS NOT ZERO -- NOT COMMITTED; the write stands in the working tree')
    return 'scan 0 ; 0 ; 0'


