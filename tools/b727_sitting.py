    p = REPOS[kernel] + '/README.md'
    text, crlf = read(p)
    para = paragraph(kernel)
    if flat(para) != flat(it['draft']):
        sys.exit('### THE LAYOUT SOURCE AND THE BANK`S DRAFT DIFFER AT [%d] -- NOTHING WRITTEN' % n)
    ln = text.split(NL)
    ln[2] = para
    text = NL.join(ln)
    for w, s in exceeds(kernel):
        L = text.split(NL)
        hit = [i for i, l in enumerate(L) if l == s]
        if hit:
            del L[hit[0]]
            text = NL.join(L)
        elif (' ' + s) in text:
            text = text.replace(' ' + s, '', 1)
        else:
            text = text.replace(s + ' ', '', 1)
    while NL + NL + NL in text:
        text = text.replace(NL + NL + NL, NL + NL)
    write(p, text, crlf)
    return kernel, 'README.md', p


