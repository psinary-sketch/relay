def read(p):
    raw = open(p, 'rb').read()
    crlf = raw.count(b'\r\n') > 0
    t = raw.decode('utf-8')
    return (t.replace('\r\n', NL) if crlf else t), crlf


def write(p, t, crlf):
    b = (t.replace(NL, '\r\n') if crlf else t).encode('utf-8')
    with open(p + '.tmp', 'wb') as fh:
        fh.write(b)
    os.replace(p + '.tmp', p)


def git(repo, *a):
    r = subprocess.run(['git', '-C', repo, *a], capture_output=True, text=True, encoding='utf-8', errors='replace')
    return r.returncode, r.stdout.strip(), r.stderr.strip()


def gh(*a):
    r = subprocess.run(['gh', *a], capture_output=True, text=True, encoding='utf-8', errors='replace')
    return r.returncode, r.stdout.strip(), r.stderr.strip()


def http(url, method='GET', body=None, token=None):
    h = {'User-Agent': 'relay-b727', 'Accept': 'application/json'}
    if token:
        h['Authorization'] = 'Bearer ' + token
    if body is not None:
        h['Content-Type'] = 'application/json'
    req = urllib.request.Request(url, method=method, headers=h, data=None if body is None else json.dumps(body).encode('utf-8'))
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            t = r.read().decode('utf-8')
            return r.status, json.loads(t) if t else {}
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode('utf-8', 'replace')[:600]


