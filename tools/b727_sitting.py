def now():
    return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())


def sha(s):
    return hashlib.sha256(s.encode('utf-8')).hexdigest()[:16]


def items():
    """the bank's items, parsed: {n: dict(title, file, line, current, draft, why, at)}."""
    L = open(BANK, encoding='utf-8').read().split(NL)
    out, cur = {}, None
    for i, l in enumerate(L, 1):
        m = re.match(r'  \[(\d+)\] (.*)$', l)
        if m:
            cur = out.setdefault(int(m.group(1)), {'title': m.group(2), 'at': i})
            continue
        m = re.match(r'    (FILE|LINE|CURRENT|DRAFT|WHY):\s+(.*)$', l)
        if m and cur is not None:
            cur[m.group(1).lower()] = m.group(2)
    return out


def exceeds(kernel):
    """the sentences of PARTS A and F of this kernel's README, as the bank carries them (F) or as [1],[2] carry them (A); the :3 line stands apart."""
    out = [('11.1', items()[2]['current'])] if kernel == 'SIDE-rcurve' else []   # ### PART A's [2]; its :3 is [1], the line the paragraph replaces
    for l in open(BANK, encoding='utf-8').read().split(NL):
        m = re.match(r'  (SIDE-\S+) README\.md :(\d+)\.(\d+) \| (.*)$', l)
        if m and m.group(1) == kernel and m.group(2) != '3':
            out.append((m.group(2) + '.' + m.group(3), m.group(4)))
    return out


def paragraph(kernel):
    """the draft's paragraph with the layout of data/b721_frozen_line_drafts.txt: the prose lines joined, the statement lines indented four as a code block."""
    L = open(DRAFTS, encoding='utf-8').read().split(NL)
    i = next(k for k, l in enumerate(L) if l.startswith('## %s ' % kernel)) + 2
    blocks, prose, code = [], [], []
    for l in L[i:]:
        if l.startswith('  GITHUB DESCRIPTION'):
            break
        if l.startswith('        '):
            if prose:
                blocks.append(' '.join(prose))
                prose = []
            code.append('    ' + l.strip())
        else:
            if code:
                blocks.append(NL.join(code))
                code = []
            prose.append(l.strip())
    blocks.append(' '.join(prose))
    return (NL + NL).join(blocks)


def flat(s):
    return ' '.join(s.split())


